"""DDS -> PostgreSQL DDL generator v2 (reconciled).
Rules: one target table per DISTINCT legacy member; identical duplicate definitions are merged
with lineage recorded; conflicting definitions are NOT merged - the majority/first-seen definition
becomes the primary table and each conflicting variant is emitted as <member>_<source>_variant
and flagged in the mapping register. Nothing is silently discarded."""
import json, csv, re, collections, hashlib

inv = json.load(open("migration/legacy_inventory.json"))
SCHEMA = {"Budget":"budget","School Map":"school_map","Technical Abstracts":"abstracts",
          "Purchases & Contracts":"purchases","Real Estate":"real_estate","Estimates (BOQ)":"estimates"}
def sqltype(f):
    n, L, d = f["name"], f["length"], f["decimals"]
    if d > 0: return f"NUMERIC({L},{d})", "numeric-decimal"
    if re.search(r"(NM|NAME|DESC|TXT|ADDR|NOTE)", n) or L >= 30: return f"VARCHAR({L})", "char-by-name/length"
    if re.search(r"(DT|DAT|DATE)$", n) and L == 8: return "INTEGER", "legacy-date-YYYYMMDD"
    if L <= 9: return "INTEGER", "numeric-int"
    if L <= 18: return "BIGINT", "numeric-bigint"
    return f"VARCHAR({L})", "char-long"

def sig(defn):
    return hashlib.sha256(json.dumps([[fld["name"], fld["length"], fld["decimals"]]
        for r in defn["records"] for fld in r["fields"]], sort_keys=False).encode()).hexdigest()[:12]

pfs = [f for f in inv["data_files"] if f["kind"] == "PF"]
by_member = collections.defaultdict(list)
for f in pfs: by_member[f["member"]].append(f)

out = ["-- GAEB PostgreSQL DDL v2 (RECONCILED) — generated by migration/gen_ddl_v2.py",
       "-- One table per distinct legacy member; duplicates merged with lineage; conflicts emitted as variants.", ""]
for s in sorted(set(SCHEMA.values())): out.append(f"CREATE SCHEMA IF NOT EXISTS {s};")
out.append("")
reg = []
table_count = 0
for member, defs in sorted(by_member.items()):
    groups = collections.defaultdict(list)
    for d in defs: groups[sig(d)].append(d)
    variants = sorted(groups.items(), key=lambda kv: -len(kv[1]))
    for i, (sg, gdefs) in enumerate(variants):
        d0 = gdefs[0]
        sch = SCHEMA.get(d0["subsystem"], "legacy")
        base = member.lower().replace("#", "n_")
        tbl = base if i == 0 else f"{base}_{(d0['source_file'] or 'variant').lower()}_variant"
        status = "Generated — pending approval" if len(variants) == 1 else ("CONFLICT — primary variant, pending customer evidence" if i == 0 else "CONFLICT — alternate variant, pending customer evidence")
        lineage = "; ".join(sorted({f"{d['library']}/{d['source_file']} ({d['pdf']})" for d in gdefs}))
        out.append(f"-- {member} | subsystem {d0['subsystem']} | definitions merged: {len(gdefs)} | signature {sg} | {status}")
        out.append(f"-- lineage: {lineage}")
        cols, pk = [], []
        for r in d0["records"]:
            for fld in r["fields"]:
                t, why = sqltype(fld)
                cols.append(f"  {fld['name'].lower()} {t}")
                reg.append([member, sch, tbl, fld["name"], fld["length"], fld["decimals"], t, why, status, lineage])
            pk = [k.lower() for k in r["keys"]]
        body = ",\n".join(cols)
        if pk and all(any(c.strip().startswith(p + " ") for c in cols) for p in pk):
            body += f",\n  PRIMARY KEY ({', '.join(pk)})"
        out.append(f"CREATE TABLE IF NOT EXISTS {sch}.{tbl} (\n{body}\n);\n")
        table_count += 1
open("migration/reconciled/schema_v2.sql", "w").write("\n".join(out))
with open("migration/reconciled/mapping_register_v2.csv", "w", newline="") as fh:
    w = csv.writer(fh)
    w.writerow(["legacy_member","target_schema","target_table","legacy_field","length","decimals","sql_type","inference_rule","approval_status","source_lineage"])
    w.writerows(reg)
print("target tables:", table_count, "| register rows:", len(reg), "| distinct members:", len(by_member))
